const FIBER_CATEGORIES = ["TRUNK", "PATCH", "ROBUST", "BREAKOUT", "AOC"];

function numberOrNull(value: string): number | null {
  const trimmed = value.trim();
  return trimmed === "" ? null : Number(trimmed);
}

function errorText(error: unknown, fallback: string): string {
  const data = (error as { response?: { data?: { detail?: unknown; errors?: unknown } } })?.response?.data;
  if (Array.isArray(data?.errors) && data.errors.length) return (data.errors as string[]).join(" ");
  if (typeof data?.detail === "string") return data.detail;
  return fallback;
}

const box = (tone: "red" | "green" | "neutral"): CSSProperties => ({
  fontSize: 13,
  marginBottom: 12,
  padding: "8px 12px",
  borderRadius: 6,
  color: tone === "red" ? "var(--red)" : tone === "green" ? "var(--green)" : "var(--text)",
  background: tone === "red" ? "var(--red-soft, #fff0f0)" : tone === "green" ? "var(--green-soft, #f0fff4)" : "var(--surface-2, rgba(127,127,127,0.08))",
});

function Field({ label, children }: { label: string; children: ReactNode }) {
  return (
    <label style={{ display: "flex", flexDirection: "column", gap: 4, fontSize: 12, color: "var(--text-muted)" }}>
      {label}
      {children}
    </label>
  );
}

/** Lista de opções do catálogo, com "Outro…" para um valor que ainda não existe. */
function SelectOrOther({
  label,
  value,
  options,
  onChange,
  copy,
  upper = false,
}: {
  label: string;
  value: string;
  options: string[];
  onChange: (value: string) => void;
  copy: Copy;
  upper?: boolean;
}) {
  const known = options.includes(value);
  const [forceOther, setForceOther] = useState(false);
  const otherMode = forceOther || (value !== "" && !known);
  return (
    <Field label={label}>
      <select
        className="input"
        value={otherMode ? "__other__" : value}
        onChange={(e) => {
          if (e.target.value === "__other__") {
            setForceOther(true);
            onChange("");
          } else {
            setForceOther(false);
            onChange(e.target.value);
          }
        }}
      >
        <option value="">{copy.select}</option>
        {options.map((option) => (
          <option key={option} value={option}>
            {option}
          </option>
        ))}
        <option value="__other__">{copy.other}</option>
      </select>
      {otherMode && (
        <input
          className="input"
          autoFocus
          value={value}
          placeholder={copy.otherPlaceholder}
          onChange={(e) => onChange(upper ? e.target.value.toUpperCase() : e.target.value)}
        />
      )}
    </Field>
  );
}

function ChoiceCards({ items, value, onPick }: { items: { value: string; label: string }[]; value: string; onPick: (value: string) => void }) {
  return (
    <div style={{ display: "grid", gridTemplateColumns: "repeat(auto-fit, minmax(170px, 1fr))", gap: 10 }}>
      {items.map((item) => {
        const active = item.value === value;
        return (
          <button
            key={item.value}
            type="button"
            onClick={() => onPick(item.value)}
            style={{
              padding: "16px 12px",
              borderRadius: 8,
              cursor: "pointer",
              fontSize: 14,
              fontWeight: active ? 600 : 400,
              border: `2px solid ${active ? "var(--primary, #2563eb)" : "var(--border)"}`,
              background: active ? "var(--primary-soft, rgba(37,99,235,0.08))" : "transparent",
              color: "var(--text)",
            }}
          >
            {item.label}
          </button>
        );
      })}
    </div>
  );
}

function Row({ label, value }: { label: string; value: ReactNode }) {
  return (
    <div style={{ display: "flex", gap: 8, fontSize: 13, padding: "4px 0" }}>
      <span style={{ color: "var(--text-muted)", minWidth: 130 }}>{label}</span>
      <span style={{ fontWeight: 500 }}>{value}</span>
    </div>
  );
}

export default function CableWizardPanel() {
  const p = usePageText(TEXT);
  const [options, setOptions] = useState<CableWizardOptions | null>(null);
  const [answers, setAnswers] = useState<Answers>(EMPTY_ANSWERS);
  const [stepIndex, setStepIndex] = useState(0);
  const [preview, setPreview] = useState<CableWizardPreview | null>(null);
  const [aliasChoice, setAliasChoice] = useState<Record<string, boolean>>({});
  const [customAliases, setCustomAliases] = useState<string[]>([]);
  const [customInput, setCustomInput] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] = useState<CableWizardResult | null>(null);

  useEffect(() => {
    cableWizardApi
      .options()
      .then(setOptions)
      .catch((err) => setError(errorText(err, p.erroGenerico)));
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const steps: StepKey[] =
    answers.medium === "COPPER"
      ? ["medium", "traits", "family", "aliases", "spec", "review"]
      : ["medium", "type", "traits", "family", "aliases", "spec", "review"];
  const current = steps[stepIndex];
  const set = <K extends keyof Answers>(key: K, value: Answers[K]) => setAnswers((prev) => ({ ...prev, [key]: value }));

  const selectedAliases = (source: CableWizardPreview | null, choice: Record<string, boolean>): string[] => {
    const fromPreview = (source?.aliases ?? [])
      .filter((entry) => entry.type === "NAME_VARIATION" && entry.state !== "conflict" && choice[entry.text])
      .map((entry) => entry.text);
    return [...new Set([...fromPreview, ...customAliases])];
  };

  const buildRequest = (source: CableWizardPreview | null, choice: Record<string, boolean>): CableWizardRequest => {
    const request: CableWizardRequest = {
      medium: answers.medium as Medium,
      preterminated: answers.preterminated,
      work_group: answers.work_group,
      reuse_family_id: source?.family.mode === "existing" ? source.family.id : null,
      aliases: selectedAliases(source, choice),
    };
    if (answers.medium === "COPPER") {
      request.copper_type = answers.copper_type;
      request.shielding = answers.shielding;
    } else {
      request.category = answers.category;
      request.fiber_count = numberOrNull(answers.fiber_count);
      request.connector_a = answers.connector_a;
      request.connector_b = answers.connector_b;
      request.legs = numberOrNull(answers.legs);
      request.speed = answers.speed;
      request.length = answers.length;
    }
    if (answers.useSpec) {
      request.spec = {
        manufacturer: answers.manufacturer,
        part_number: answers.part_number,
        fiber_type: answers.fiber_type,
        jacket_color: answers.jacket_color,
        polarity: answers.polarity,
      };
    }
    return request;
  };

  const runPreview = async (): Promise<CableWizardPreview | null> => {
    setBusy(true);
    setError(null);
    try {
      const data = await cableWizardApi.preview(buildRequest(preview, aliasChoice));
      setPreview(data);
      setAliasChoice((prev) => {
        const next = { ...prev };
        for (const entry of data.aliases) {
          if (!(entry.text in next)) next[entry.text] = entry.type === "NAME_VARIATION" && entry.suggested && entry.state !== "conflict";
        }
        return next;
      });
      // Primeira vez: já deixa o grupo sugerido selecionado ("NONE" = sem grupo).
      setAnswers((prev) => ({ ...prev, work_group: prev.work_group || data.family.work_group_suggestion || "NONE" }));
      return data;
    } catch (err) {
      setError(errorText(err, p.erroGenerico));
      return null;
    } finally {
      setBusy(false);
    }
  };

  const goNext = async () => {
    setError(null);
    if (current === "medium" && !answers.medium) return;
    if (current === "type" && !answers.category) return;
    if (current === "traits" || current === "spec") {
      if (current === "spec" && answers.useSpec && !answers.manufacturer.trim() && !answers.part_number.trim()) {
        setError(p.spec.hint);
        return;
      }
      const data = await runPreview();
      if (!data) return;
    }
    setStepIndex((index) => Math.min(index + 1, steps.length - 1));
  };

  const goBack = () => {
    setError(null);
    setStepIndex((index) => Math.max(index - 1, 0));
  };

  const handleMedium = (value: string) => {
    setAnswers({ ...EMPTY_ANSWERS, medium: value as Medium, category: value === "COPPER" ? "COPPER" : "" });
    setPreview(null);
    setAliasChoice({});
    setCustomAliases([]);
  };

  const handleRegister = async () => {
    setBusy(true);
    setError(null);
    try {
      const created = await cableWizardApi.create(buildRequest(preview, aliasChoice));
      setResult(created);
    } catch (err) {
      setError(errorText(err, p.erroGenerico));
    } finally {
      setBusy(false);
    }
  };

  const reset = () => {
    setAnswers(EMPTY_ANSWERS);
    setStepIndex(0);
    setPreview(null);
    setAliasChoice({});
    setCustomAliases([]);
    setCustomInput("");
    setResult(null);
    setError(null);
    cableWizardApi.options().then(setOptions).catch(() => undefined);
  };

  const addCustomAlias = () => {
    const text = customInput.trim();
    if (!text) return;
    setCustomAliases((prev) => (prev.includes(text) ? prev : [...prev, text]));
    setCustomInput("");
  };

  const connectorOptions = options?.connectors ?? [];
  const isBreakout = answers.category === "BREAKOUT";
  const isAoc = answers.category === "AOC";

  const renderTraits = () => {
    if (!options) return null;
    if (answers.medium === "COPPER") {
      return (
        <div style={{ display: "grid", gridTemplateColumns: "repeat(auto-fit, minmax(200px, 1fr))", gap: 12 }}>
          <Field label={p.traits.copperType}>
            <select className="input" value={answers.copper_type} onChange={(e) => set("copper_type", e.target.value)}>
              <option value="">{p.select}</option>
              {options.copper_types.map((type) => (
                <option key={type} value={type}>
                  {type}
                </option>
              ))}
            </select>
          </Field>
          <Field label={p.traits.shielding}>
            <select className="input" value={answers.shielding} onChange={(e) => set("shielding", e.target.value)}>
              {options.shieldings.map((shield) => (
                <option key={shield} value={shield}>
                  {shield}
                </option>
              ))}
            </select>
          </Field>
        </div>
      );
    }
    return (
      <div style={{ display: "grid", gridTemplateColumns: "repeat(auto-fit, minmax(220px, 1fr))", gap: 12 }}>
        {isAoc ? (
          <>
            <Field label={p.traits.speed}>
              <input className="input" value={answers.speed} onChange={(e) => set("speed", e.target.value.toUpperCase())} />
            </Field>
            <Field label={p.traits.length}>
              <input className="input" value={answers.length} onChange={(e) => set("length", e.target.value.toUpperCase())} />
            </Field>
            <SelectOrOther label={p.traits.connectorA} value={answers.connector_a} options={connectorOptions} onChange={(v) => set("connector_a", v)} copy={p} upper />
          </>
        ) : (
          <>
            {isBreakout ? (
              <Field label={p.traits.legs}>
                <input className="input" type="number" min={1} value={answers.legs} onChange={(e) => set("legs", e.target.value)} />
              </Field>
            ) : (
              <SelectOrOther
                label={p.traits.fiberCount}
                value={answers.fiber_count}
                options={options.fiber_counts.map(String)}
                onChange={(v) => set("fiber_count", v)}
                copy={p}
              />
            )}
            {answers.category !== "ROBUST" && (
              <>
                <SelectOrOther
                  label={isBreakout ? p.traits.connectorATrunk : p.traits.connectorA}
                  value={answers.connector_a}
                  options={connectorOptions}
                  onChange={(v) => set("connector_a", v)}
                  copy={p}
                  upper
                />
                <SelectOrOther
                  label={isBreakout ? p.traits.connectorBLegs : p.traits.connectorB}
                  value={answers.connector_b}
                  options={connectorOptions}
                  onChange={(v) => set("connector_b", v)}
                  copy={p}
                  upper
                />
              </>
            )}
          </>
        )}
      </div>
    );
  };

  const renderStep = () => {
    switch (current) {
      case "medium":
        return (
          <>
            <h4 style={{ margin: "0 0 12px" }}>{p.medium.title}</h4>
            <ChoiceCards
              value={answers.medium}
              onPick={handleMedium}
              items={[
                { value: "FIBER", label: p.medium.FIBER },
                { value: "COPPER", label: p.medium.COPPER },
              ]}
            />
          </>
        );
      case "type":
        return (
          <>
            <h4 style={{ margin: "0 0 12px" }}>{p.type.title}</h4>
            <ChoiceCards
              value={answers.category}
              onPick={(value) => set("category", value)}
              items={FIBER_CATEGORIES.map((value) => ({ value, label: p.type.options[value] }))}
            />
          </>
        );
      case "traits":
        return (
          <>
            <h4 style={{ margin: "0 0 12px" }}>{p.traits.title}</h4>
            {renderTraits()}
          </>
        );
      case "family": {
        const family = preview?.family;
        if (!family) return null;
        const existing = family.mode === "existing";
        return (
          <>
            <h4 style={{ margin: "0 0 12px" }}>{p.family.title}</h4>
            <div style={box(existing ? "neutral" : "green")}>
              <strong>{existing ? p.family.existingTitle : p.family.newTitle}</strong>
              <div style={{ marginTop: 2 }}>{existing ? p.family.existingBody : p.family.newBody}</div>
            </div>
            <div style={{ border: "1px solid var(--border)", borderRadius: 8, padding: 12, marginBottom: 14 }}>
              <div style={{ fontSize: 11, color: "var(--text-muted)", marginBottom: 4 }}>{p.family.generated}</div>
              <Row label={p.family.code} value={family.code} />
              <Row label={p.family.name} value={family.name} />
            </div>
            {!existing && (
              <div style={{ display: "grid", gridTemplateColumns: "repeat(auto-fit, minmax(220px, 1fr))", gap: 12 }}>
                <Field label={p.family.workGroup}>
                  <select className="input" value={answers.work_group} onChange={(e) => set("work_group", e.target.value)}>
                    <option value="NONE">{p.family.noGroup}</option>
                    {(options?.work_groups ?? []).map((group) => (
                      <option key={group.value} value={group.value}>
                        {group.label}
                        {group.value === family.work_group_suggestion ? ` (${p.family.suggested})` : ""}
                      </option>
                    ))}
                  </select>
                </Field>
                <Field label={p.family.preterminated}>
                  <select className="input" value={answers.preterminated ? "1" : "0"} onChange={(e) => set("preterminated", e.target.value === "1")}>
                    <option value="1">{p.yes}</option>
                    <option value="0">{p.no}</option>
                  </select>
                </Field>
              </div>
            )}
          </>
        );
      }
      case "aliases": {
        // Só as sugestões do sistema; os aliases digitados aparecem na lista própria abaixo.
        const entries = (preview?.aliases ?? []).filter((entry) => entry.type === "NAME_VARIATION" && entry.suggested);
        return (
          <>
            <h4 style={{ margin: "0 0 4px" }}>{p.aliases.title}</h4>
            <p style={{ fontSize: 13, color: "var(--text-muted)", margin: "0 0 12px" }}>{p.aliases.intro}</p>
            {entries.map((entry) => {
              const blocked = entry.state === "conflict";
              return (
                <label key={entry.text} style={{ display: "flex", gap: 8, alignItems: "center", fontSize: 14, padding: "4px 0", opacity: blocked ? 0.6 : 1 }}>
                  <input
                    type="checkbox"
                    disabled={blocked}
                    checked={!blocked && !!aliasChoice[entry.text]}
                    onChange={(e) => setAliasChoice((prev) => ({ ...prev, [entry.text]: e.target.checked }))}
                  />
                  <span>{entry.text}</span>
                  {entry.state === "exists" && <span style={{ fontSize: 12, color: "var(--text-muted)" }}>({p.aliases.exists})</span>}
                  {blocked && <span style={{ fontSize: 12, color: "var(--red)" }}>{entry.message}</span>}
                </label>
              );
            })}
            {customAliases.map((alias) => (
              <div key={alias} style={{ display: "flex", gap: 8, alignItems: "center", fontSize: 14, padding: "4px 0" }}>
                <Icon name="check" />
                <span>{alias}</span>
                <button className="btn btn-outline btn-sm" type="button" onClick={() => setCustomAliases((prev) => prev.filter((item) => item !== alias))}>
                  {p.aliases.remove}
                </button>
              </div>
            ))}
            <div style={{ display: "flex", gap: 8, marginTop: 12 }}>
              <input
                className="input"
                style={{ flex: 1 }}
                value={customInput}
                placeholder={p.aliases.placeholder}
                onChange={(e) => setCustomInput(e.target.value)}
                onKeyDown={(e) => {
                  if (e.key === "Enter") {
                    e.preventDefault();
                    addCustomAlias();
                  }
                }}
              />
              <button className="btn btn-outline" type="button" onClick={addCustomAlias}>
                <Icon name="add" /> {p.aliases.add}
              </button>
            </div>
            <p style={{ fontSize: 12, color: "var(--text-muted)", marginTop: 12 }}>{p.aliases.partNumberAuto}</p>
          </>
        );
      }
      case "spec":
        return (
          <>
            <h4 style={{ margin: "0 0 12px" }}>{p.spec.title}</h4>
            <p style={{ fontSize: 13, margin: "0 0 10px" }}>{p.spec.ask}</p>
            <div style={{ marginBottom: 14 }}>
              <ChoiceCards
                value={answers.useSpec ? "yes" : "no"}
                onPick={(value) => set("useSpec", value === "yes")}
                items={[
                  { value: "yes", label: p.spec.yes },
                  { value: "no", label: p.spec.skip },
                ]}
              />
            </div>
            {answers.useSpec && options && (
              <div style={{ display: "grid", gridTemplateColumns: "repeat(auto-fit, minmax(220px, 1fr))", gap: 12 }}>
                <SelectOrOther label={p.spec.manufacturer} value={answers.manufacturer} options={options.manufacturers} onChange={(v) => set("manufacturer", v)} copy={p} />
                <Field label={p.spec.partNumber}>
                  <input className="input" value={answers.part_number} onChange={(e) => set("part_number", e.target.value)} />
                </Field>
                <SelectOrOther label={p.spec.fiberType} value={answers.fiber_type} options={options.fiber_types} onChange={(v) => set("fiber_type", v)} copy={p} upper />
                <SelectOrOther label={p.spec.color} value={answers.jacket_color} options={options.colors} onChange={(v) => set("jacket_color", v)} copy={p} upper />
                <SelectOrOther label={p.spec.polarity} value={answers.polarity} options={options.polarities} onChange={(v) => set("polarity", v)} copy={p} upper />
              </div>
            )}
            {answers.useSpec && <p style={{ fontSize: 12, color: "var(--text-muted)", marginTop: 10 }}>{p.spec.hint}</p>}
          </>
        );
      case "review": {
        if (!preview) return null;
        const aliasList = selectedAliases(preview, aliasChoice);
        const partNumber = preview.aliases.find((entry) => entry.type === "PART_NUMBER");
        return (
          <>
            <h4 style={{ margin: "0 0 12px" }}>{p.review.title}</h4>
            <div style={{ border: "1px solid var(--border)", borderRadius: 8, padding: 12, marginBottom: 12 }}>
              <Row label={p.review.family} value={`${preview.family.code} — ${preview.family.name}`} />
              <Row label="" value={preview.family.mode === "new" ? p.review.willCreate : p.review.willReuse} />
              <Row
                label={p.review.aliases}
                value={[...aliasList, ...(partNumber ? [partNumber.text] : [])].join(" · ") || p.review.none}
              />
              <Row label={p.review.spec} value={preview.spec ? `${preview.spec.code} — ${preview.spec.name}` : p.review.none} />
            </div>
            {preview.errors.length > 0 ? (
              <div style={box("red")}>
                <strong>{p.review.issues}</strong>
                <ul style={{ margin: "4px 0 0 18px" }}>
                  {preview.errors.map((message) => (
                    <li key={message}>{message}</li>
                  ))}
                </ul>
              </div>
            ) : (
              <div style={box("green")}>{p.review.ok}</div>
            )}
          </>
        );
      }
      default:
        return null;
    }
  };

  const stepper = (
    <div style={{ display: "flex", gap: 6, marginBottom: 16, flexWrap: "wrap" }}>
      {steps.map((key, index) => {
        const active = index === stepIndex;
        const done = index < stepIndex;
        return (
          <span
            key={key}
            style={{
              fontSize: 12,
              padding: "4px 10px",
              borderRadius: 999,
              border: "1px solid var(--border)",
              background: active ? "var(--primary, #2563eb)" : "transparent",
              color: active ? "#fff" : done ? "var(--text)" : "var(--text-muted)",
              fontWeight: active ? 600 : 400,
            }}
          >
            {index + 1}. {p.steps[key]}
          </span>
        );
      })}
    </div>
  );

  if (result) {
    return (
      <div style={{ padding: 4 }}>
        <h3 style={{ margin: "0 0 12px", fontSize: 16 }}>{p.done.title}</h3>
        <div style={box("green")}>
          <div>
            {result.family_created ? p.done.familyCreated : p.done.familyReused}: <strong>{result.family.code}</strong> — {result.family.name}
          </div>
          <div>{p.done.aliasesCreated(result.aliases.length)}</div>
          {result.spec && (
            <div>
              {p.done.specCreated}: <strong>{result.spec.code}</strong> — {result.spec.name}
            </div>
          )}
        </div>
        <button className="btn btn-primary" onClick={reset}>
          <Icon name="add" /> {p.newModel}
        </button>
      </div>
    );
  }

  const isLast = current === "review";
  const nextDisabled =
    busy ||
    (current === "medium" && !answers.medium) ||
    (current === "type" && !answers.category) ||
    (current === "traits" && !options);

  return (
    <div style={{ padding: 4 }}>
      <div style={{ marginBottom: 14 }}>
        <h3 style={{ margin: 0, fontSize: 16 }}>{p.titulo}</h3>
        <p style={{ fontSize: 13, color: "var(--text-muted)", margin: "4px 0 0" }}>{p.subtitulo}</p>
      </div>
      {stepper}
      {error && <div style={box("red")}>{error}</div>}
      <div style={{ minHeight: 160, marginBottom: 16 }}>{renderStep()}</div>
      <div style={{ display: "flex", gap: 8 }}>
        <button className="btn btn-outline" onClick={goBack} disabled={busy || stepIndex === 0}>
          {p.back}
        </button>
        {isLast ? (
          <button className="btn btn-primary" onClick={handleRegister} disabled={busy || !preview?.can_create}>
            <Icon name="save" /> {busy ? p.registering : p.register}
          </button>
        ) : (
          <button className="btn btn-primary" onClick={goNext} disabled={nextDisabled}>
            {busy ? p.checking : p.next}
          </button>
        )}
      </div>
    </div>
  );
}
